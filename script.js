/* ============================================================
   script.js — проверка формы обратной связи на JavaScript

   КАК ЭТО РАБОТАЕТ, ОДНИМ АБЗАЦЕМ:
   1. Ждём загрузки страницы.
   2. Находим форму по её id.
   3. Вешаем «обработчик события» на submit (отправку формы).
   4. При отправке сначала отменяем стандартное поведение
      (чтобы страница НЕ перезагружалась).
   5. Проверяем поля: имя непустое, email непустой и похож на email,
      сообщение непустое.
   6. Ошибку показываем красным текстом, всё ок — alert().
   ============================================================ */

// document — это вся наша страница, объект из браузера.
// "DOMContentLoaded" — событие: «HTML полностью загрузился».
// addEventListener — подписаться на событие: «когда оно случится — выполни мою функцию».
document.addEventListener('DOMContentLoaded', function () {

    // --- ШАГ 1. Находим нужные элементы страницы по их id ---

    // getElementById — взять элемент с атрибутом id="feedback-form" (наша форма)
    var form = document.getElementById('feedback-form');

    // Поля формы тоже достаём по id
    var nameField = document.getElementById('name');       // поле «Имя»
    var emailField = document.getElementById('email');     // поле «Email»
    var messageField = document.getElementById('message'); // поле «Сообщение»
    var errorField = document.getElementById('error');     // абзац для ошибок

    // --- ШАГ 2. Подписываемся на событие submit (попытка отправки формы) ---

    // Функция срабатывает КАЖДЫЙ раз при нажатии кнопки «Отправить»
    form.addEventListener('submit', function (event) {

        // event.preventDefault() — «отменить действие по умолчанию».
        // По умолчанию браузер отправляет форму на сервер и перезагружает
        // страницу. Нам сервер не нужен, поэтому говорим: стоп, не делай этого.
        event.preventDefault();

        // Очищаем старое сообщение об ошибке (на случай, если оно было)
        errorField.textContent = '';

        // trim() — обрезать пробелы по краям строки.
        // «   Ичиго   » превратится в «Ичиго».
        // Без trim пользователь мог бы «обмануть» проверку одними пробелами.
        var name = nameField.value.trim();
        var email = emailField.value.trim();
        var message = messageField.value.trim();

        // --- ШАГ 3. ПРОВЕРКА ПОЛЕЙ ---

        // Проверка 1: имя непустое.
        // if (условие) { действие } — если условие верно, выполни действие.
        if (name === '') {
            errorField.textContent = 'Ошибка: поле «Имя» не заполнено.';
            nameField.focus(); // ставим курсор в это поле — удобно пользователю
            return; // return выходит из функции — остальные проверки не нужны
        }

        // Проверка 2: email непустой.
        if (email === '') {
            errorField.textContent = 'Ошибка: поле «Email» не заполнено.';
            emailField.focus();
            return;
        }

        // Проверка 3: email похож на настоящий адрес.
        // Регулярное выражение — шаблон строки. Вкратце:
        //   ^        — начало строки
        //   [^\s@]+  — любые символы КРОМЕ пробела и @, хотя бы один
        //   @        — собачка
        //   [^\s@]+  — снова символы без пробела и @ (домен)
        //   \.       — точка (точка в рег. выражениях означает «любой символ»,
        //              поэтому экранируем обратным слэшем \.)
        //   [^\s@]+  — окончание домена, например .com, .ru
        //   $        — конец строки
        // Метод .test(email) вернёт true, если строка подходит под шаблон.
        var emailPattern = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
        if (!emailPattern.test(email)) {
            errorField.textContent = 'Ошибка: введите корректный email, например best@cats.ru';
            emailField.focus();
            return;
        }

        // Проверка 4: сообщение непустое.
        if (message === '') {
            errorField.textContent = 'Ошибка: поле «Сообщение» не заполнено.';
            messageField.focus();
            return;
        }

        // --- ШАГ 4. Если все return не сработали — значит всё заполнено правильно ---
        alert('Данные формы успешно проверены! Отправка на сервер пока не настроена');

        // Бонус: можно очистить форму после успешной проверки
        form.reset();
    });
});
